def test_concurrent_sends_start_one_turn(
    client: TestClient, conversation: Conversation, backend: FakeBackend
) -> None:
    backend.released = False
    send = lambda: client.post(f"/c/{conversation.id}/messages", data={"content": "Hi"})  # noqa: E731
    responses = concurrently(backend, send, send, send)
    assert sorted(r.status_code for r in responses) == [200, 409, 409]
    assert len(conversation.active_path()) == 2


def test_reconnecting_clients_follow_the_same_generation(
    client: TestClient, conversation: Conversation, backend: FakeBackend
) -> None:
    backend.released = False
    client.post(f"/c/{conversation.id}/messages", data={"content": "Hi"})
    reply = conversation.active_path()[1]
    follow = lambda: stream(client, conversation, reply.id)  # noqa: E731
    bodies = concurrently(backend, follow, follow)

    for body in bodies:
        # Each client gets every chunk, then `done` with the finished message,
        # not a busy one that would reconnect again.
        assert body.count("event: content") == 3
        assert 'class="msg assistant done"' in body.split("event: done", 1)[1]
    assert len(backend.calls) == 1


def test_generation_finishes_without_a_client(
    client: TestClient, conversation: Conversation
) -> None:
    client.post(f"/c/{conversation.id}/messages", data={"content": "Hi"})
    reply = conversation.active_path()[1]
    deadline = time.monotonic() + 5
    while reply.is_busy and time.monotonic() < deadline:
        time.sleep(0.01)
    assert reply.status == "done"
    assert reply.content == "Hello, <world>!\nBye"


