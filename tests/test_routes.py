from openai.types.chat import ChatCompletionMessageParam

from simplechat.config import Settings
from simplechat.llm import ChunkKind, ThinkingOptions
from simplechat.main import create_app
from simplechat.store import Conversation, Store

SETTINGS = Settings(
    ollama_url="http://unused",
    ollama_api_key="unused",
    default_model="",
    host="127.0.0.1",
    port=8000,
)

# llama3 cannot think; qwen3 can.
QWEN_THINKING = ThinkingOptions(levels=["none", "low", "high"], default="high")


class FakeBackend:
    def __init__(
        self, chunks: list[tuple[ChunkKind, str]] | None = None, fail: bool = False
    ) -> None:
        self.chunks = chunks or [
            ("content", "Hello"),
            ("content", ", <world>"),
            ("content", "!\nBye"),
        ]
        self.fail = fail
        # Set to False to hold replies in the "streaming" state until set back to True.
        self.released = True
        self.calls: list[tuple[str, list[ChatCompletionMessageParam], str]] = []

    async def list_models(self) -> list[str]:
        return ["llama3", "qwen3"]

    async def thinking_options(self, model: str) -> ThinkingOptions | None:
        return QWEN_THINKING if model == "qwen3" else None

    async def stream_chat(
        self, model: str, messages: list[ChatCompletionMessageParam], thinking: str = ""
    ) -> AsyncIterator[tuple[ChunkKind, str]]:
        self.calls.append((model, messages, thinking))
        if self.fail:
            raise APIConnectionError(request=None)  # type: ignore[arg-type]
        while not self.released:
            await asyncio.sleep(0.005)
        for chunk in self.chunks:
            yield chunk


@pytest.fixture
def backend() -> FakeBackend:
    return FakeBackend()


@pytest.fixture
def store() -> Store:
    return Store()


@pytest.fixture
def client(backend: FakeBackend, store: Store) -> Iterator[TestClient]:
    # Used as a context manager so one event loop runs across requests; replies are
    # generated by background tasks on that loop.
    with TestClient(create_app(settings=SETTINGS, backend=backend, store=store)) as client:
        yield client


@pytest.fixture
def conversation(client: TestClient, store: Store) -> Conversation:
    client.post("/c")
    return store.recent()[0]


def stream(client: TestClient, conversation: Conversation, message_id: str) -> str:
    """Wait for a reply to finish and return its SSE stream."""
    return client.get(f"/c/{conversation.id}/stream/{message_id}").text


def concurrently[T](backend: FakeBackend, *calls: Callable[[], T]) -> list[T]:
    """Run requests at the same time while the backend holds replies, then release it.

    Replies are generated in the background, so a stream opened after a reply
    finished only gets `done`. Holding the backend lets requests attach first.
    """
    with ThreadPoolExecutor(max_workers=len(calls)) as pool:
        futures = [pool.submit(call) for call in calls]
        time.sleep(0.1)  # let the requests reach the app
        backend.released = True
        return [future.result(timeout=5) for future in futures]


